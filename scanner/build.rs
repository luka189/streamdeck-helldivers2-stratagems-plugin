//! Builds the data the reader needs into the crate (`Data::Embedded`): ../data/stratagems.json and the
//! pictures in ../data/icons_144 and ../data/status. The plugin reads them from there, as Marketplace DRM
//! keeps a plugin from reading its own files. Writes `$OUT_DIR/embedded_data.rs`, a table sorted by path.

use std::fmt::Write as _;
use std::path::PathBuf;

const DIRS: [&str; 2] = ["icons_144", "status"];

fn main() {
    let data = PathBuf::from(std::env::var_os("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR")).join("../data");
    println!("cargo::rerun-if-changed=build.rs");
    println!("cargo::rerun-if-changed={}", data.join("stratagems.json").display());
    // a directory is scanned whole: a picture added, changed or removed builds the table again
    for dir in DIRS {
        println!("cargo::rerun-if-changed={}", data.join(dir).display());
    }

    let mut files = vec![("stratagems.json".to_string(), data.join("stratagems.json"))];
    for dir in DIRS {
        let entries = std::fs::read_dir(data.join(dir)).unwrap_or_else(|e| panic!("{}: {e}", data.join(dir).display()));
        for entry in entries {
            let path = entry.expect("directory entry").path();
            if path.is_file() && path.extension().is_some_and(|x| x == "png") {
                let name = path.file_name().and_then(|n| n.to_str()).unwrap_or_else(|| panic!("{}: not UTF-8", path.display()));
                files.push((format!("{dir}/{name}"), path.clone()));
            }
        }
    }
    files.sort();

    let mut out = String::from("// Generated by build.rs from ../data; do not edit.\npub static FILES: &[(&str, &[u8])] = &[\n");
    for (name, path) in &files {
        writeln!(out, "    ({name:?}, include_bytes!({:?})),", path.display().to_string()).unwrap();
    }
    out.push_str("];\n");
    let dest = PathBuf::from(std::env::var_os("OUT_DIR").expect("OUT_DIR")).join("embedded_data.rs");
    std::fs::write(&dest, out).unwrap_or_else(|e| panic!("{}: {e}", dest.display()));
}
